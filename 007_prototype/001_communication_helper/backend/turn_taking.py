"""話者交代（ターンテイキング）の制御に使う指示文。

フロントエンドは次のように使う。
1. ユーザ発話が確定するたびに、JUDGE_INSTRUCTIONS と JUDGE_TOOL で「会話に残らない裏側の応答（out-of-band）」を
   生成させ、関数呼び出しの引数で RESPOND / BACKCHANNEL / WAIT を判定する
   （Realtime モデル自身が音声を聞いて判定するため速い。関数呼び出しを強制して出力形式のぶれを防ぐ）
2. RESPOND → 通常の応答、BACKCHANNEL → BACKCHANNEL_PROMPT を差し込んで相づちだけ、WAIT → 何もしない
3. 誰も話さない時間が一定以上続いたら、PROACTIVE_PROMPT を差し込んで AI から話しかける
   （感情推定で判定した会話の段階が CLOSING_STAGES なら、CLOSING_PROMPT で一度だけ会話を締め、以降は話しかけない。
    通常の話しかけには、感情推定が出した「次にすべきこと」を添える）
差し込んだ 1 回きりの指示は、応答が終わったら会話から削除する（古い指示が文脈に残って混乱するのを防ぐ）
"""

# ターン判定の指示（out-of-band 応答の instructions として使う）
JUDGE_INSTRUCTIONS = """あなたは会話のターン判定器です。会話に参加してはいけません。
ここまでの会話（user=先輩、assistant=後輩）のうち、先輩の最新の発話だけに注目し、その直後に後輩が何をすべきかを判定します。

判定基準:
- RESPOND（後輩が返事をする番）: 最新の発話が、質問（〜？/〜かな？/〜の？/〜る？）、呼びかけ（ちょっといい？）、依頼・お願い（〜してもらえる？/〜お願い/〜してほしい。）、意見や返事を求める、話題を振る、のいずれかで、文として言い終わっている。
- BACKCHANNEL（相づちだけ）: 最新の発話が「〜で、」「〜けど、」「〜って、」「〜から、」のように文の途中で切れていて、先輩がまだ続きを話す。または説明・報告を続けている途中。
- WAIT（何も言わない）: 「えっと」「うーん」「どうしようかな」など、言いよどみ・考え中・独り言。

例:
「ちょっといいかな。」→ RESPOND
「今日の17時までに直してほしいんだけど、」→ BACKCHANNEL
「それでさ、その資料っていうのが、」→ BACKCHANNEL
「議事録っていつ終わりそう？」→ RESPOND
「えーっと…」→ WAIT
「最近、週末とか何してるの？」→ RESPOND

判定結果は decide_turn 関数で報告すること。後輩として返事をしてはいけない。"""

# ターン判定の結果を受け取る関数（tool_choice=required で必ず呼ばせる）
JUDGE_TOOL = {
    "type": "function",
    "name": "decide_turn",
    "description": "先輩の最新の発話の直後に、後輩がすべきこと（返事 / 相づち / 待機）を報告する",
    "parameters": {
        "type": "object",
        "properties": {"decision": {"type": "string", "enum": ["RESPOND", "BACKCHANNEL", "WAIT"]}},
        "required": ["decision"],
    },
}

# 相づちだけ返させるときに差し込むシステムメッセージ
BACKCHANNEL_PROMPT = (
    "（この直後の1回だけ）先輩はまだ話の途中です。"
    "「はい」「ええ」「なるほど」など、話の腰を折らない短い相づちを一言だけ返してください。それ以外は話さないこと。"
)

# 沈黙が続いたときに AI から話しかけさせるシステムメッセージ
PROACTIVE_PROMPT = (
    "（この直後の1回だけ）先輩がしばらく黙っています。"
    "この会話でのあなたの目的と、ここまでの流れ（「# 会話の進行状況」があればそれ）を踏まえて、"
    "後輩の立場として自然な一言で話しかけてください（例: 相談や用件の続き、内容の確認、話題の提示。緊張しているなら遠慮がちに）。"
    "先輩を気づかったり、先輩に質問や相談を促したりする言い方"
    "（「他に気になる点はありますか」「何かありますか」「大丈夫でしょうか」など）はしないこと。"
)

# まだ誰も話していないうちに沈黙が続いたとき（先輩から話しかけるシナリオの冒頭など）のシステムメッセージ
IDLE_OPENING_PROMPT = (
    "（この直後の1回だけ）まだ会話は始まっておらず、先輩はそばにいるのに黙っています。"
    "現在の状況に合わせて、後輩の立場で自然に短く声をかけてください。"
    "業務の場面（先輩に声をかけられそうな場面）なら、「お疲れさまです、何かご用でしょうか」のように控えめに尋ねる程度にする。"
    "雑談の場面（休憩・移動・朝の挨拶など）なら、挨拶と、その場に合った軽い一言（天気、お昼ごはん、週明けなど）だけにし、"
    "用件を尋ねたり、時間をもらおうとしたりしない。"
    "「何かお手伝いできることはありますか」のような手伝いを申し出る言い方や、まだ聞いていない話の内容に触れる言い方はしないこと。"
)

# 会話の段階が「まとめ」「終了」のときに、沈黙が続いたら一度だけ会話を締めさせるシステムメッセージ
# （「まとめ」は結論が出て締めに向かう段階なので、そこで沈黙したら会話の終わりとみなす）
CLOSING_STAGES = ["まとめ", "終了"]
CLOSING_PROMPT = (
    "（この直後の1回だけ）先輩がしばらく黙っています。用件や話はすでに一段落しています。"
    "新しい話題を出したり、先輩に質問を促したりせず、後輩の立場で短く会話を締めてください。"
    "まだお礼や挨拶をしていなければ伝え、すでに伝えているなら繰り返さず、自分の作業に戻る・その場を離れることを短く伝えるだけにする。"
    "言い回しは状況に合わせて自分で考えること。"
)
