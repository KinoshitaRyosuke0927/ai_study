"""単元5 演習5(ウェルチの検定の出力)の数値を、表示する要約統計量から計算して確かめる。"""
from scipy import stats

for n1, m1, s1, n2, m2, s2 in [(10, 48.2, 4.1, 10, 54.6, 7.6), (12, 48.2, 4.1, 10, 54.6, 7.6), (12, 48.2, 4.5, 10, 54.6, 7.0)]:
    v1, v2 = s1 ** 2 / n1, s2 ** 2 / n2
    t = (m1 - m2) / (v1 + v2) ** 0.5
    df = (v1 + v2) ** 2 / (v1 ** 2 / (n1 - 1) + v2 ** 2 / (n2 - 1))
    p = 2 * stats.t.cdf(-abs(t), df)
    print(n1, m1, s1, n2, m2, s2, "t", round(t, 3), "df", round(df, 2), "p", round(p, 4), "n1+n2-2", n1 + n2 - 2)
