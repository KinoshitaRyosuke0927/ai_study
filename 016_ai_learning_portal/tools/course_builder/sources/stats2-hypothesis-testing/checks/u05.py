"""単元5(2つの母平均の差の検定)の解説・演習に使う数値を計算して確かめる。"""
import numpy as np
from scipy import stats

t = stats.t
for df in (4, 20, 12):
    print(f"t df={df}: 0.025 {t.ppf(0.975, df):.3f}  0.05 {t.ppf(0.95, df):.3f}")

# 解説: 分散既知 x1=78, x2=74, σ1²=36, σ2²=64, n1=n2=25
se = (36 / 25 + 64 / 25) ** 0.5
print("分散既知 SE", se, "z", (78 - 74) / se)
# 解説: 等分散 n1=10, x1=75, s1²=36 / n2=12, x2=70, s2²=40
sp2 = (9 * 36 + 11 * 40) / 20
se = (sp2 * (1 / 10 + 1 / 12)) ** 0.5
print("等分散 sp2", sp2, "SE", round(se, 4), "t", round(5 / se, 3), "両側p", round(2 * (1 - t.cdf(5 / se, 20)), 4))
# 解説: ウェルチ(同じ数値で)
v1, v2 = 36 / 10, 40 / 12
se = (v1 + v2) ** 0.5
df = (v1 + v2) ** 2 / (v1 ** 2 / 9 + v2 ** 2 / 11)
print("ウェルチ SE", round(se, 4), "t", round(5 / se, 3), "自由度", round(df, 2))
# 解説: 対応のあるデータ(差 3,5,2,6,4)
d = np.array([3, 5, 2, 6, 4])
s = d.std(ddof=1)
print("対応あり 平均", d.mean(), "偏差平方和", ((d - d.mean()) ** 2).sum(), "分散", s ** 2, "SE", round(s / 5 ** 0.5, 4), "t", round(d.mean() / (s / 5 ** 0.5), 3))

# 演習1: 分散既知
print("演習1 z", (53 - 48) / (20 / 10 + 30 / 15) ** 0.5)
# 演習2: プールした分散
print("演習2 sp2", round((7 * 10 + 5 * 15) / 12, 4))
# 演習3: 対応あり(差 2,-1,3,4,2)
d = np.array([2, -1, 3, 4, 2])
s = d.std(ddof=1)
print("演習3 平均", d.mean(), "偏差平方和", ((d - d.mean()) ** 2).sum(), "分散", s ** 2, "SE", round(s / 5 ** 0.5, 4), "t", round(d.mean() / (s / 5 ** 0.5), 4))
