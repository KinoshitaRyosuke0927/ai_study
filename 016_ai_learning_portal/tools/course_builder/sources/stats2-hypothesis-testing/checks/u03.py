"""単元3(母平均の検定)の解説・演習に使う数値を計算して確かめる。"""
from scipy import stats

t = stats.t
# t 分布のパーセント点
for df in (4, 9, 15, 19, 29):
    print(f"t df={df}: 0.05 {t.ppf(0.95, df):.3f}  0.025 {t.ppf(0.975, df):.3f}  0.005 {t.ppf(0.995, df):.3f}")

# 解説: z 検定(内容量)μ0 = 500、σ = 4、n = 16、標本平均 502.2
z = (502.2 - 500) / (4 / 16 ** 0.5)
print("z検定 SE", 4 / 4, "z", round(z, 3), "両側p", round(2 * (1 - stats.norm.cdf(z)), 4))
# 解説: t 検定 μ0 = 12、n = 10、標本平均 12.6、s = 1.2
se = 1.2 / 10 ** 0.5
tt = (12.6 - 12) / se
print("t検定 SE", round(se, 4), "t", round(tt, 3), "両側p", round(2 * (1 - t.cdf(tt, 9)), 4))

# 演習1: z = (53.5 - 50) / (10 / 5)
print("演習1 z", (53.5 - 50) / (10 / 5))
# 演習3: t = (23 - 21) / (4 / 4)
tt = (23 - 21) / (4 / 16 ** 0.5)
print("演習3 t", tt, "両側p", round(2 * (1 - t.cdf(tt, 15)), 4), "片側p", round(1 - t.cdf(tt, 15), 4))
# 演習5: ソフトの出力 t = 2.45、df = 19
print("演習5 両側p", round(2 * (1 - t.cdf(2.45, 19)), 4), "片側p", round(1 - t.cdf(2.45, 19), 4))
# 出力の例: n = 20、標本平均 52.4、s = 4.38、μ0 = 50
se = 4.38 / 20 ** 0.5
print("出力例 SE", round(se, 4), "t", round((52.4 - 50) / se, 3))
