"""単元6(母分散の比・母比率の差の検定)の解説・演習に使う数値を計算して確かめる。"""
from scipy import stats

F, N = stats.f, stats.norm
for d1, d2 in [(10, 15), (15, 10), (12, 9), (9, 12)]:
    print(f"F({d1},{d2}): 上側0.025 {F.ppf(0.975, d1, d2):.3f}  上側0.05 {F.ppf(0.95, d1, d2):.3f}")
print("下側 2.5% 点 F(10,15) = 1 / F0.025(15,10) =", round(1 / F.ppf(0.975, 15, 10), 4), "直接", round(F.ppf(0.025, 10, 15), 4))

# 解説: 分散の比 n1 = 11, s1² = 24 / n2 = 16, s2² = 10
f = 24 / 10
print("分散比 F", f, "両側p", round(2 * (1 - F.cdf(f, 10, 15)), 4))
# 解説: 比率の差 A 60/200, B 45/200
p1, p2, pp = 60 / 200, 45 / 200, 105 / 400
se = (pp * (1 - pp) * (1 / 200 + 1 / 200)) ** 0.5
z = (p1 - p2) / se
print("比率の差 p1", p1, "p2", p2, "プール", pp, "SE", round(se, 4), "z", round(z, 3), "両側p", round(2 * (1 - N.cdf(z)), 4))

# 演習1・2: F = 18 / 8(n1 = 13, n2 = 10)
f = 18 / 8
print("演習1 F", f, "自由度", (12, 9), "両側p", round(2 * (1 - F.cdf(f, 12, 9)), 4))
# 演習3・4: 30/100 と 20/100
pp = 50 / 200
se = (pp * (1 - pp) * (1 / 100 + 1 / 100)) ** 0.5
print("演習3 プール", pp, "演習4 SE", round(se, 5), "z", round((0.3 - 0.2) / se, 4))
