"""小テストに使う数値を計算して確かめる。"""
from scipy import stats

print("問5 z", (104 - 100) / (12 / 36 ** 0.5))
print("問6 t", (53 - 48) / (6 / 9 ** 0.5), "自由度", 8, "t0.025(8)", round(stats.t.ppf(0.975, 8), 3))
print("問8 z", (0.28 - 0.2) / (0.2 * 0.8 / 100) ** 0.5)
print("問9 χ2", 20 * 15 / 10, "上側5%(20)", round(stats.chi2.ppf(0.95, 20), 3))
print("問10 t", 3 / (9 * (1 / 8 + 1 / 8)) ** 0.5)
print("問12 F", 20 / 8)
print("問13 プール", (40 + 30) / 200)
o = [25, 15, 20, 22, 18, 20]
print("問14 χ2", sum((x - 20) ** 2 / 20 for x in o), "合計", sum(o))
print("問15 期待度数", 40 * 30 / 100)
