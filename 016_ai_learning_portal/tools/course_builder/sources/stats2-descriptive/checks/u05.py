"""単元5(標準化・変動係数・指数化)の解説・演習に使う数値を計算して確かめる。"""
import numpy as np
from scipy import stats

# 解説: 1次変換(摂氏 → 華氏)
print("華氏 平均", 1.8 * 20 + 32, "標準偏差", 1.8 * 5)
# 解説: 偏差値の例と正規分布の割合
print("偏差値例 z", (75 - 60) / 10, "偏差値", 50 + 10 * (75 - 60) / 10)
for k in (1, 2, 3):
    print(f"±{k}σ の割合", round(stats.norm.cdf(k) - stats.norm.cdf(-k), 4), f"偏差値 {50 + 10 * k} 以上の割合", round(1 - stats.norm.cdf(k), 4))
# 解説: 変動係数
print("ゾウ CV", 400 / 5000, "ネズミ CV", 0.004 / 0.02)
# 解説: 指数化
price = np.array([180, 186, 195, 210, 231])
print("指数", (price / price[0] * 100).round(1).tolist(), "2024→2025", round((231 / 210 - 1) * 100, 2))
print("指数の差", round(231 / 180 * 100 - 210 / 180 * 100, 1))

# 演習1: 偏差値
z = (46 - 55) / 12
print("演習1 z", z, "偏差値", 50 + 10 * z)
# 演習2: 3 科目の z
for name, score, mean, sd in [("数学", 70, 60, 20), ("英語", 66, 58, 8), ("国語", 75, 70, 10)]:
    print("演習2", name, (score - mean) / sd)
# 演習3: y = -2x + 50
print("演習3 平均", -2 * 20 + 50, "標準偏差", abs(-2) * 4)
# 演習4: 変動係数
print("演習4 A", 10 / 50, "B", 30 / 200, "B 平均/SD", round(200 / 30, 2))
# 演習5: 指数の比から変化率
print("演習5", (132 / 110 - 1) * 100)
