"""講座1(データの理解)の解説・演習を考えるための集計。"""
import pandas as pd
pd.set_option("display.width", 120)
tr = pd.read_csv("train.csv"); te = pd.read_csv("test.csv")
print(tr.shape, te.shape)
print(tr.dtypes)
print(tr.isna().mean().round(3).sort_values(ascending=False))
print(te.isna().sum())
print("生存率", tr.Survived.mean().round(4))
print(tr.groupby("Sex").Survived.agg(["mean", "count"]).round(3))
print(tr.groupby("Pclass").Survived.agg(["mean", "count"]).round(3))
print(tr.groupby("Embarked").Survived.agg(["mean", "count"]).round(3))
print(pd.crosstab(tr.Sex, tr.Pclass, values=tr.Survived, aggfunc="mean").round(3))
print(tr.groupby("Pclass").Age.apply(lambda s: s.isna().mean()).round(3))
print(tr.Age.describe().round(2)); print(tr.Fare.describe().round(2)); print("Fare skew", tr.Fare.skew().round(3))
tr["AgeGroup"] = pd.cut(tr.Age, [0, 12, 18, 30, 50, 80])
print(tr.groupby("AgeGroup", observed=True).Survived.agg(["mean", "count"]).round(3))
print(tr.groupby(pd.qcut(tr.Fare, 4), observed=True).Survived.agg(["mean", "count"]).round(3))
print(tr.SibSp.value_counts().sort_index()); print(tr.Parch.value_counts().sort_index())
fam = tr.SibSp + tr.Parch + 1
print(tr.groupby(fam).Survived.agg(["mean", "count"]).round(3))
print("Boat あり の生存率", tr[tr.Boat.notna()].Survived.mean().round(3), "Boat なし", tr[tr.Boat.isna()].Survived.mean().round(3))
print("Body あり の生存率", tr[tr.Body.notna()].Survived.mean().round(3))
print("Cabin あり生存率", tr[tr.Cabin.notna()].Survived.mean().round(3), "なし", tr[tr.Cabin.isna()].Survived.mean().round(3))
print(tr[["Survived","Pclass","Age","SibSp","Parch","Fare"]].corr().round(3))
print(tr.Name.str.extract(r",\s*([^.]+)\.")[0].value_counts().head(10))
