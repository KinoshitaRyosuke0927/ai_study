"""単元1(母集団と標本・標本平均の分布)の解説・演習に使う数値を計算して確かめる。"""
# 解説: 身長 μ = 170、σ = 6、n = 9
print("標本平均の SD", 6 / 9 ** 0.5)
# 解説: サイコロ1個の母平均・母分散
vals = range(1, 7)
mu = sum(vals) / 6
var = sum((v - mu) ** 2 for v in vals) / 6
print("サイコロ μ", mu, "σ2", round(var, 4), "n=4 の標本平均の分散", round(var / 4, 4))
# 解説: 有限母集団修正 N = 100、n = 20、σ² = 25
f = (100 - 20) / (100 - 1)
print("修正係数", round(f, 4), "V(標本平均)", round(f * 25 / 20, 4), "SD", round((f * 25 / 20) ** 0.5, 4))
# 解説: 標本比率 p = 0.3、n = 100
print("標本比率の SD", round((0.3 * 0.7 / 100) ** 0.5, 4))

# 演習
print("演習1 SE", 12 / 36 ** 0.5)
print("演習2 V", 50 / 25)
print("演習3 標準誤差を 1/3 → n を", 3 ** 2, "倍")
f = (500 - 100) / (500 - 1)
print("演習5 修正係数", round(f, 4))
