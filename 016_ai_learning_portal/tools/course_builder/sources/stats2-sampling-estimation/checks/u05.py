"""単元5(点推定と推定量の性質)の解説・演習に使う数値を計算して確かめる。"""
import numpy as np

# 解説: n で割る分散の期待値 (n-1)/n σ²(σ² = 4、n = 5)
print("n で割る分散の期待値", 4 * 4 / 5)
# 解説: (X1 + 2X2)/3 と (X1 + X2)/2 の分散(σ² = 9)
print("(X1+2X2)/3 の分散", (1 + 4) / 9 * 9, "(X1+X2)/2 の分散", 9 / 2)
# 解説: シミュレーション(図の数値の確認)σ² = 4、n = 5
rng = np.random.default_rng(3)
x = rng.normal(0, 2, (100000, 5))
print("n-1 で割る平均", round(x.var(axis=1, ddof=1).mean(), 3), "n で割る平均", round(x.var(axis=1, ddof=0).mean(), 3))

# 演習1: σ² = 10、n = 5
print("演習1", 10 * 4 / 5)
# 演習2: 期待値の係数
for name, coef in [("T1", [1 / 3, 1 / 3, 1 / 3]), ("T2", [1 / 2, 1 / 2, 0]), ("T3", [2 / 4, 1 / 4, 0]), ("T4", [1, 0, 0])]:
    print("演習2", name, "期待値の係数", round(sum(coef), 4), "分散の係数", round(sum(c * c for c in coef), 4))
# 演習3: (X1 + 2X2)/3、σ² = 9
print("演習3", (1 + 4) / 9 * 9)
