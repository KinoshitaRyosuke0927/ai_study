"""単元2(大数の法則・中心極限定理・チェビシェフの不等式)の解説・演習に使う数値を計算して確かめる。"""
from scipy import stats

N = stats.norm
# 解説: サイコロ 36 回の平均
var = 35 / 12
se = (var / 36) ** 0.5
z = (4 - 3.5) / se
print("サイコロ σ2", round(var, 4), "SE", round(se, 4), "z", round(z, 3), "P(平均>4)", round(1 - N.cdf(z), 4))
# 解説: チェビシェフ k = 2 と正規分布の比較
print("チェビシェフ k=2 上限", 1 / 4, "正規分布での確率", round(2 * (1 - N.cdf(2)), 4))
# 演習1・2
print("演習1 k=3", round(1 / 9, 4))
print("演習2 40〜60(平均50, SD5)k=2 → 少なくとも", 1 - 1 / 4)
# 演習3: μ = 100、σ = 15、n = 25、P(平均 > 106)
se = 15 / 5
print("演習3 SE", se, "z", (106 - 100) / se, "P", round(1 - N.cdf(2), 4))
