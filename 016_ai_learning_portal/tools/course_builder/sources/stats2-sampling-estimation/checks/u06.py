"""単元6(母平均の区間推定)の解説・演習に使う数値を計算して確かめる。"""
import math

from scipy import stats

T = stats.t
for df in (8, 15, 24):
    print(f"t df={df}: 上側0.025 {T.ppf(0.975, df):.3f}")
# 解説: σ 既知 x̄ = 172.3、σ = 6、n = 36
se = 6 / 6
print("σ既知 95%", round(172.3 - 1.96 * se, 2), round(172.3 + 1.96 * se, 2), " 99%", round(172.3 - 2.576 * se, 3), round(172.3 + 2.576 * se, 3))
# 解説: σ 未知 n = 16、x̄ = 50.2、s = 4
t = T.ppf(0.975, 15)
print("σ未知 95%", round(50.2 - t * 1, 3), round(50.2 + t * 1, 3))
# 解説: 必要な標本の大きさ σ = 10、誤差 2
print("必要な n", (1.96 * 10 / 2) ** 2, math.ceil((1.96 * 10 / 2) ** 2))

# 演習1: x̄ = 80、σ = 12、n = 16
print("演習1 下限", 80 - 1.96 * 3)
# 演習2: n = 9、x̄ = 25、s = 3
print("演習2 上限", round(25 + T.ppf(0.975, 8) * 1, 3))
# 演習3: σ = 8、誤差 2
print("演習3", (1.96 * 8 / 2) ** 2, math.ceil((1.96 * 8 / 2) ** 2))
