"""単元3(正規分布と標準正規分布表・二項分布の正規近似)の解説・演習に使う数値を計算して確かめる。"""
from scipy import stats

N = stats.norm
# 解説: 標準正規分布表(上側確率)
for z in (0.5, 1.0, 1.28, 1.5, 1.645, 1.95, 1.96, 2.0, 2.326, 2.5, 2.576, 3.0):
    print(f"P(Z > {z}) = {1 - N.cdf(z):.4f}")
# 解説: X ~ N(60, 10²)
print("P(X>75)", round(1 - N.cdf(1.5), 4), "P(50<X<70)", round(N.cdf(1) - N.cdf(-1), 4), "上側5%点", 60 + 1.645 * 10)
# 解説: 再生性 X ~ N(50, 3²)、Y ~ N(40, 4²)
print("X+Y 平均", 90, "SD", (9 + 16) ** 0.5, "X-Y 平均", 10, "SD", (9 + 16) ** 0.5)
# 解説: 二項分布 B(100, 0.5)、P(X >= 60)
print("連続修正なし", round(1 - N.cdf((60 - 50) / 5), 4), "連続修正あり z", (59.5 - 50) / 5, round(1 - N.cdf(1.9), 4), "正確", round(1 - stats.binom.cdf(59, 100, 0.5), 4))

# 演習
print("演習1 z", (62 - 50) / 8, round(1 - N.cdf(1.5), 4))
print("演習2", round(N.cdf(1) - N.cdf(-1), 4))
print("演習3", 200 + 1.96 * 20)
print("演習4 SD", (9 + 16) ** 0.5, "P(X+Y>60)", round(1 - N.cdf((60 - 50) / 5), 4))
print("演習5 z", (219.5 - 200) / 10, round(1 - N.cdf(1.95), 4), "正確", round(1 - stats.binom.cdf(219, 400, 0.5), 4))
