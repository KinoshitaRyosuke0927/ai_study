"""単元1〜4(データ収集・確率・ベイズの定理)の解説・演習に使う数値を計算して確かめる。"""
from fractions import Fraction as Fr
from math import comb

# 単元1: 系統抽出の間隔、比例配分
print("u1 系統抽出 例 2000/100 =", 2000 / 100, " 演習 1200/60 =", 1200 / 60)
for sizes, n in [([4000, 3500, 2500], 200), ([600, 300, 100], 50)]:
    total = sum(sizes)
    print("u1 比例配分", sizes, n, [n * s / total for s in sizes])

# 単元3: 確率の基礎
print("u3 サイコロ2個 和が7", Fr(6, 36), " 少なくとも1回6(3回)", round(1 - (5 / 6) ** 3, 4))
print("u3 加法定理 0.5 + 0.4 - 0.2 =", 0.5 + 0.4 - 0.2)
# 解説: トランプ ハートかつ絵札
print("u3 ハート", Fr(13, 52), "絵札", Fr(12, 52), "ハートの絵札", Fr(3, 52), "ハートまたは絵札", Fr(13 + 12 - 3, 52))
# 解説: クロス表から条件付き確率(男性 40 人中購入 12)
print("u3 P(購入|男性)", 12 / 40, " P(男性|購入)", round(12 / 39, 4))
# 演習: 独立の判定 P(A)=0.4、P(B)=0.5、P(A∩B)=0.2
print("u3 独立判定", 0.4 * 0.5)
# 演習: 少なくとも1回(4回、成功確率 0.2)
print("u3 少なくとも1回 0.2 x 4", round(1 - 0.8 ** 4, 4))
# 演習: 取り出し(赤3白2から非復元で2個とも赤)
print("u3 2個とも赤", Fr(3, 5) * Fr(2, 4), float(Fr(3, 5) * Fr(2, 4)))

# 単元4: ベイズの定理
prev, sens, fp = 0.01, 0.99, 0.05
pos = prev * sens + (1 - prev) * fp
print("u4 検査 陽性の確率", round(pos, 4), "陽性的中率", round(prev * sens / pos, 4))
print("u4 10000人 有病", 10000 * prev, "真陽性", 10000 * prev * sens, "偽陽性", 9900 * fp)
# 演習: 工場 A 60% 不良 2%、B 40% 不良 5%
pd = 0.6 * 0.02 + 0.4 * 0.05
print("u4 不良率", pd, "P(B|不良)", round(0.4 * 0.05 / pd, 4), "P(A|不良)", round(0.6 * 0.02 / pd, 4))
# 演習: 迷惑メール 20%、「無料」を含む 迷惑 50% / 通常 5%
pw = 0.2 * 0.5 + 0.8 * 0.05
print("u4 迷惑メール P(含む)", pw, "P(迷惑|含む)", round(0.2 * 0.5 / pw, 4))
